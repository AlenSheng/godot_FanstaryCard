# Edit precisely one actual cell in the isolated workbook. Shared strings and
# every other ZIP member stay unchanged; no generated byte is hand-edited.
M = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'
REL = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
PKG = 'http://schemas.openxmlformats.org/package/2006/relationships'
ET.register_namespace('', M)
with zipfile.ZipFile(workbook) as archive:
    infos = archive.infolist()
    entries = {item.filename: archive.read(item.filename) for item in infos}
root = ET.fromstring(entries['xl/workbook.xml'])
relationships = {node.attrib['Id']: node.attrib['Target'] for node in
    ET.fromstring(entries['xl/_rels/workbook.xml.rels']).findall('{' + PKG + '}Relationship')}
sheet = next(node for node in root.findall('.//{' + M + '}sheet') if node.attrib['name'] == 'Cards')
target = relationships[sheet.attrib['{' + REL + '}id']].replace('\\', '/')
target = target.lstrip('/') if target.startswith('/') else target if target.startswith('xl/') else 'xl/' + target
target = posixpath.normpath(target)
shared = []
if 'xl/sharedStrings.xml' in entries:
    shared = [''.join(node.itertext()) for node in ET.fromstring(entries['xl/sharedStrings.xml']).findall('{' + M + '}si')]
tree = ET.fromstring(entries[target])


def value(cell):
    if cell.attrib.get('t') == 'inlineStr':
        return ''.join(node.text or '' for node in cell.findall('.//{' + M + '}t'))
    node = cell.find('{' + M + '}v')
    raw = '' if node is None else node.text or ''
    return shared[int(raw)] if cell.attrib.get('t') == 's' and raw else raw


cells = {node.attrib['r']: node for node in tree.findall('.//{' + M + '}c')}
before = {key: value(node) for key, node in cells.items()}
columns = {key.rstrip('0123456789'): text for key, text in before.items() if key.endswith('1') and key[:-1].isalpha()}
id_column = next(column for column, name in columns.items() if name == 'id')
name_column = next(column for column, name in columns.items() if name == 'name')
row_number = next(key[len(id_column):] for key, text in before.items()
                  if key.startswith(id_column) and key[len(id_column):].isdigit() and text == 'C01')
reference = name_column + row_number
cell = cells[reference]
old_name = value(cell)
assert old_name
for child in list(cell):
    cell.remove(child)
cell.set('t', 'inlineStr')
text = ET.SubElement(ET.SubElement(cell, '{' + M + '}is'), '{' + M + '}t')
text.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
text.text = old_name + ' [PR13 isolated source mismatch]'
after = {key: value(node) for key, node in cells.items()}
assert [key for key in before if before[key] != after[key]] == [reference]
entries[target] = ET.tostring(tree, encoding='utf-8', xml_declaration=True)
